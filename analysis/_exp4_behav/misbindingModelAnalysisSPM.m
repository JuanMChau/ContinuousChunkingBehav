function output = fixNumberString(value)
    timer = 0;
    if (value<=1e-3)
        while (value<1)
            value = value*10;
            timer = timer+1;
        end
    end
    
    if (timer>0)
        output = sprintf("$%.3g \\times 10^{-%d}$",value,timer);
    elseif (value>1)
        output = sprintf("%.3g",value);
    else
        output = sprintf("%.3f",value);
    end
end